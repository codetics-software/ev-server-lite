package fr.codetics.ev_server.core

import io.swagger.v3.oas.models.OpenAPI
import io.swagger.v3.oas.models.info.Contact
import io.swagger.v3.oas.models.info.Info
import org.springframework.context.annotation.Bean
import org.springframework.context.annotation.Configuration
import org.springframework.scheduling.annotation.EnableScheduling
import org.springframework.transaction.PlatformTransactionManager
import org.springframework.transaction.support.TransactionTemplate

@Configuration(proxyBeanMethods = false)
@EnableScheduling
class AppConfiguration {
    @Bean
    fun transactionTemplate(manager: PlatformTransactionManager): TransactionTemplate {
        return TransactionTemplate(manager)
    }

    @Bean
    fun openApi(): OpenAPI {
        val contact = Contact()
            .name("Kevin Vavelin — Codetics")
            .url("https://codetics.fr")
        val information = Info()
            .title("EV Supervision Lite")
            .version("v1")
            .description("Generated by Codetics with OpenApi")
            .contact(contact)

        return OpenAPI().info(information)
    }
}
