export function valueLabel(value: string) {
  if (value.startsWith("STATION_COMMAND_")) {
    return t("Commande · {operation}", {
      operation: values[value.slice(16)] ?? t("Opération de la borne"),
    });
  }
  return values[value] ?? value;
}

